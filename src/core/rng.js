// Gerador pseudoaleatório determinístico (mulberry32) — permite gravar/repor o estado.
export class RNG {
  constructor(seed = Date.now()) { this.s = (seed >>> 0) || 1; }
  next() {
    let a = (this.s = (this.s + 0x6D2B79F5) | 0);
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  }
  get state() { return this.s; }
  set state(v) { this.s = v | 0; }
  seed(v) { this.s = (v >>> 0) || 1; }
  rand() { return this.next(); }
  range(a, b) { return a + (b - a) * this.next(); }
  int(a, b) { return Math.floor(a + (b - a + 1) * this.next()); }
  chance(p) { return this.next() < p; }
  pick(arr) { return arr[Math.floor(this.next() * arr.length)]; }
  pickW(arr, weights) {
    const w = weights || arr.map(x => (x && x.weight != null ? x.weight : 1));
    let tot = 0; for (const x of w) tot += Math.max(0, x);
    let r = this.next() * tot;
    for (let i = 0; i < arr.length; i++) { r -= Math.max(0, w[i]); if (r <= 0) return arr[i]; }
    return arr[arr.length - 1];
  }
  gauss(mean = 0, sd = 1) {
    let u = 0, v = 0;
    while (u === 0) u = this.next();
    while (v === 0) v = this.next();
    return mean + sd * Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
  }
  shuffle(arr) {
    const a = arr.slice();
    for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(this.next() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; }
    return a;
  }
  sample(arr, n) { return this.shuffle(arr).slice(0, n); }
}

